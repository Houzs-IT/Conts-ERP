import { type Env, json, fail, audit } from '../../../_lib/db';
import { requireSession } from '../../../_lib/auth';
import { companyDetails, printPage, esc } from '../../../_lib/letterhead';
import { currentTemplate, agreementValues, renderAgreement } from '../../../_lib/agreement';

/** GET /api/units/:id/agreement[?check=1] — the unit's management agreement, generated from the template in Settings
 *  and the unit, owner and contract on file: a print-ready page (Save as PDF from the browser). With ?check=1, only
 *  what is still missing, as JSON, so the screen can say what to fill in before offering the button. It carries the
 *  owner's full IC and bank account, so it is for finance and management, and each generation is audited. */
export const onRequestGet: PagesFunction<Env> = async ({ request, env, params }) => {
  const { session, response } = await requireSession(request, env);
  if (!session) return response!;
  if (!session.manage) return fail('FORBIDDEN', 'Agreements are generated by finance and management.', 403);
  const id = String(params.id);
  const template = await currentTemplate(env);
  if (!template) return fail('NOT_READY', 'There is no agreement template yet. Ask an administrator to apply the latest database update.', 501);
  const data = await agreementValues(env, id, template.body);
  if (!data) return fail('NOT_FOUND', 'That unit no longer exists.', 404);
  const url = new URL(request.url);
  if (url.searchParams.get('check')) {
    return json({ ready: data.missing.length === 0, missing: data.missing, template: { version: template.version, title: template.title } });
  }
  if (data.missing.length) {
    return fail('INCOMPLETE', `Fill these in first: ${data.missing.map(m => `${m.label} (on ${m.where || 'Settings'})`).join('; ')}.`, 409);
  }
  await audit(env, { actorId: session.userId, actorLabel: session.fullName, action: 'contract.agreement_generated', entityTable: 'units', entityId: id,
    after: { contractId: data.contractId, templateVersion: template.version } });
  const company = await companyDetails(env);
  const body = `<div class="lh-title"><h1>${esc(template.title)}</h1><span class="lh-docno">${esc(data.values.unit_code)}</span></div>
<style>.ag-h{font-size:12pt;margin:16px 0 4px;} .ag-p{margin:0 0 10px;text-align:justify;}</style>
${renderAgreement(template.body, data.values)}
<p class="lh-sub lh-noprint">Template version ${template.version}. Use the browser's Print, then Save as PDF.</p>`;
  return printPage({ company, title: `${template.title} - ${data.values.building} ${data.values.unit_code}`, body,
    filename: `agreement-${data.values.building}-${data.values.unit_code}.html` });
};
