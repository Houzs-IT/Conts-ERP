// Writes functions/_lib/apiRoutes.generated.ts: every GET handler under functions/api, in the order Cloudflare Pages
// tries them, for the AI Connector's in-process reads (functions/_lib/mcpDispatch.ts, mcpRoutes.ts).
//
//   node scripts/gen-api-routes.mjs           rewrite the file (npm run build does this first)
//   node scripts/gen-api-routes.mjs --check   exit 1 when the file is stale (npm run check, CI)
//
// The route path and the order follow wrangler's own filepath routing (generateConfigFromFileTree and compareRoutes in
// wrangler-dist/cli.js): index files answer their folder, [id] is one segment (:id), [[path]] any number (:path*).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const API = path.join(ROOT, 'functions', 'api');
const OUT = path.join(ROOT, 'functions', '_lib', 'apiRoutes.generated.ts');

function files(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...files(full));
    else if (/\.ts$/.test(e.name) && e.name !== '_middleware.ts') out.push(full);
  }
  return out;
}

/** wrangler's compareRoutes. */
function compareRoutes(a, b) {
  const segs = p => p.slice(1).split('/').filter(Boolean);
  const sa = segs(a.path), sb = segs(b.path);
  if (sa.length !== sb.length) return sb.length - sa.length;
  for (let i = 0; i < sa.length; i++) {
    const wa = sa[i].includes('*'), wb = sb[i].includes('*');
    const pa = sa[i].includes(':'), pb = sb[i].includes(':');
    if (wa && !wb) return 1;
    if (!wa && wb) return -1;
    if (pa && !pb) return 1;
    if (!pa && pb) return -1;
  }
  if (a.method && !b.method) return -1;
  if (!a.method && b.method) return 1;
  return a.path.localeCompare(b.path);
}

export function build() {
  const routes = [];
  const problems = [];
  for (const full of files(API)) {
    const rel = path.relative(path.join(ROOT, 'functions'), full).split(path.sep).join('/');
    const text = fs.readFileSync(full, 'utf8');
    if (/export\s*\{[^}]*\bonRequest/.test(text)) problems.push(`${rel}: exports a handler with export { ... }; the generator reads only export const / function`);
    // The connector's own endpoints never answer a connector read (functions/_lib/mcpAccess.ts blocks them), and leaving
    // them out keeps the table from importing the modules that import it.
    if (/^api\/(mcp|ai-connector)(\/|\.ts$)/.test(rel)) continue;
    const names = [...text.matchAll(/export\s+(?:const|async\s+function|function)\s+(onRequest(?:Get)?)\b/g)].map(m => m[1]);
    if (!names.length) continue;
    let route = rel.replace(/\.ts$/, '');
    if (/(^|\/)index$/.test(route)) route = route.replace(/\/?index$/, '');
    route = `/${route}`.replace(/\[\[(\w+)\]\]/g, ':$1*').replace(/\[(\w+)\]/g, ':$1');
    const mod = `../${rel.replace(/\.ts$/, '')}`;
    for (const name of new Set(names)) routes.push({ path: route, method: name === 'onRequestGet' ? 'GET' : '', mod, name });
  }
  const seen = new Map();
  for (const r of routes) {
    const key = `${r.method} ${r.path}`;
    if (seen.has(key)) problems.push(`${key} is answered by both ${seen.get(key)} and ${r.mod}`);
    seen.set(key, r.mod);
  }
  routes.sort(compareRoutes);
  const mods = [...new Set(routes.map(r => r.mod))].sort();
  const alias = new Map(mods.map((m, i) => [m, `r${i}`]));
  const text = [
    '// GENERATED by scripts/gen-api-routes.mjs from the functions/api file tree. Do not edit: run `node scripts/gen-api-routes.mjs`.',
    '// Every GET handler, in the order Cloudflare Pages tries them, for the AI Connector\'s in-process reads (mcpDispatch.ts).',
    "import type { ApiRoute } from './mcpRoutes';",
    ...mods.map(m => `import * as ${alias.get(m)} from '${m}';`),
    '',
    '// Built on first use, not at load: a handler module that is still loading is never read.',
    'let routes: ApiRoute[] | undefined;',
    'export function apiRoutes(): ApiRoute[] {',
    '  return routes ??= [',
    ...routes.map(r => `    { path: '${r.path}', method: '${r.method}', handler: ${alias.get(r.mod)}.${r.name} },`),
    '  ];',
    '}',
    '',
  ].join('\n');
  return { text, problems, count: routes.length };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { text, problems, count } = build();
  if (problems.length) { for (const p of problems) console.error(`gen-api-routes: ${p}`); process.exit(1); }
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (process.argv.includes('--check')) {
    if (current !== text) { console.error('functions/_lib/apiRoutes.generated.ts is stale: run `node scripts/gen-api-routes.mjs` and commit it.'); process.exit(1); }
    console.log(`apiRoutes.generated.ts is current (${count} GET routes).`);
  } else {
    if (current !== text) fs.writeFileSync(OUT, text);
    console.log(`apiRoutes.generated.ts: ${count} GET routes.`);
  }
}
