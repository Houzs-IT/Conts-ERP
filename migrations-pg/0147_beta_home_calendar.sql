-- REVERSAL: drop table public.project_beta_events, public.project_beta_appointments, public.project_beta_note_days, public.project_beta_design;
-- Beta Home, Projects and Calendar in the mockup's own format (owner, 23 Oct 2026; plan:
-- docs/superpowers/plans/2026-10-23-beta-project-workspace.md section 10). Staging-only screens read these; production
-- gets the empty tables because every route that touches them answers 404 there (BETA_ENABLED is not set in
-- wrangler.production.toml).
--
-- * project_beta_design: per project, when the 3D and the 2D work start, who draws them, and the day the PO was done.
--   No row = nothing set yet (the screens fall back to the site measure and the file dates).
-- * project_beta_note_days: how many days one amendment round (a project_design_notes row) lasts. No row = 3 days.
-- * project_beta_appointments: the site measure, carpentry measure and site briefing of a project, one of each kind.
-- * project_beta_events: the Calendar's own entries. project_id is null for internal work that belongs to no project.
--
-- APPLY: by hand, staging first, then production (node scripts/migrate-pg.mjs --env-file=<file>, dry-run first).
set local search_path = public, extensions;

create table public.project_beta_design (
  project_id bigint primary key references public.projects(id) on delete cascade,
  company_id bigint not null references public.companies(id),
  start_3d_on date,
  start_2d_on date,
  person_3d_id bigint references public.project_people(id) on delete set null,
  person_2d_id bigint references public.project_people(id) on delete set null,
  po_done_on date,
  updated_by bigint,
  updated_at timestamptz not null default now()
);

create table public.project_beta_note_days (
  note_id bigint primary key references public.project_design_notes(id) on delete cascade,
  days integer not null check (days between 1 and 60)
);

create table public.project_beta_appointments (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  company_id bigint not null references public.companies(id),
  kind text not null check (kind in ('site_measure', 'carpentry_measure', 'site_briefing')),
  on_date date not null,
  at_time time,
  person_id bigint references public.project_people(id) on delete set null,
  with_text text,
  done_at timestamptz,
  created_by bigint,
  created_at timestamptz not null default now(),
  unique (project_id, kind)
);

create table public.project_beta_events (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id),
  project_id bigint references public.projects(id) on delete cascade,
  on_date date not null,
  at_time time,
  type text not null check (type in ('client', 'measure', 'briefing', 'meeting', 'w3d', 'w2d', 'amend', 'po', 'update')),
  note text,
  person_id bigint references public.project_people(id) on delete set null,
  done boolean not null default false,
  created_by bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index project_beta_events_company_day_idx on public.project_beta_events (company_id, on_date);

alter table public.project_beta_design owner to scm_engine;
alter table public.project_beta_note_days owner to scm_engine;
alter table public.project_beta_appointments owner to scm_engine;
alter table public.project_beta_events owner to scm_engine;
alter table public.project_beta_design enable row level security;
alter table public.project_beta_note_days enable row level security;
alter table public.project_beta_appointments enable row level security;
alter table public.project_beta_events enable row level security;
revoke all on public.project_beta_design from anon, authenticated;
revoke all on public.project_beta_note_days from anon, authenticated;
revoke all on public.project_beta_appointments from anon, authenticated;
revoke all on public.project_beta_events from anon, authenticated;
