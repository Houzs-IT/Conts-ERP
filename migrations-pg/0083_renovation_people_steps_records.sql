-- The simplified renovation project (owner decisions 11 Oct 2026, docs/superpowers/specs/2026-10-11-renovation-simplified-project.md).
--
-- * project_people: one people master per company (sales, designers, renovation PICs, admin, boss, site crew and
--   contractors). Every "pick a person" field on a project points here; user_id optionally ties a person to an
--   engine login.
-- * project_flow_steps: the 6-step main flow per company. step_key has a fixed meaning (the rule that derives it);
--   label, order and active are the company's to change in Project Maintenance.
-- * projects gains the people links, a manual step (holds until the data moves past it), a hold flag (in defect /
--   on hold) and source / source_ref.
-- * project_flow_log: every hand move of the step and every hold change, with who and when.
-- * project_key_moves: who passed the unit key to whom on which date; the latest move names the current holder.
-- * project_design_records / project_design_files: the site measure (date + who) and the 2D / 3D drawings, many
--   versions, in one place on the project. A file is stored in R2 (r2_key) or, for imported history, linked by URL.
-- source ('app' | 'import') + source_ref (the Notion page id) let the Notion importer upsert without duplicates.
set local search_path = public, extensions;

create table public.project_people (
  id bigint generated by default as identity primary key,
  company_id bigint not null default 1 references public.companies(id),
  name text not null,
  roles text[] not null default '{}',
  active boolean not null default true,
  user_id bigint,
  phone text,
  notes text,
  source text not null default 'app',
  source_ref text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_people_name_check check (length(trim(name)) > 0),
  constraint project_people_roles_check check (roles <@ array['sales', 'designer', 'reno_pic', 'admin', 'boss', 'site_crew']::text[]),
  constraint project_people_source_check check (source in ('app', 'import'))
);
create unique index project_people_source_ref_unique on public.project_people (company_id, source_ref) where source_ref is not null;
create index project_people_company_idx on public.project_people (company_id, active, name);

create table public.project_flow_steps (
  id bigint generated by default as identity primary key,
  company_id bigint not null default 1 references public.companies(id),
  step_key text not null,
  label text not null,
  sort_order integer not null default 0,
  active boolean not null default true,
  updated_at timestamptz not null default now(),
  constraint project_flow_steps_key_check check (step_key in ('design', 'signed', 'ordering', 'renovation', 'handover', 'closed')),
  constraint project_flow_steps_label_check check (length(trim(label)) > 0),
  constraint project_flow_steps_unique unique (company_id, step_key)
);

insert into public.project_flow_steps (company_id, step_key, label, sort_order)
select co.id, s.step_key, s.label, s.sort_order
  from public.companies co
 cross join (values ('design', 'Design', 10), ('signed', 'Signed', 20), ('ordering', 'Ordering', 30),
                    ('renovation', 'Renovation', 40), ('handover', 'Handover', 50), ('closed', 'Closed', 60))
       as s(step_key, label, sort_order)
on conflict (company_id, step_key) do nothing;

