-- Renovation project screens, owner requests of 14 Oct 2026.
--
-- * project_attendees: the people attending a project (multi-select from project_people). Together with the
--   Project PIC (projects.reno_pic_person_id, unchanged column, new label) it replaces Sales / Designer / Renovation
--   PIC on the screen. projects.sales_person_id and designer_person_id stay as they are for their other readers;
--   both are copied into the attending set once, here.
-- * project_procurement_dates: a PO date and a delivery date per product category (sub_code = '') and per
--   sub-category of the renovation catalog (scm.product_category_groups / scm.product_sub_categories, by code).
--   A sub-category follows its category (mode 'follow', its own dates unused), has its own dates ('own') or none
--   ('none'). Effective dates are computed when read (services/renovation/procurement.ts); later they will drive
--   automatic purchase orders.
-- * project_design_notes: the change log on the 3D and the 2D (when, who asked, what to change).
-- * project_design_files gains submitted_on (the day a version was handed in) and next_person_id (on a 3D: who
--   will draw the 2D).
set local search_path = public, extensions;

create table public.project_attendees (
  project_id bigint not null references public.projects(id) on delete cascade,
  person_id bigint not null references public.project_people(id) on delete cascade,
  created_at timestamptz not null default now(),
  created_by bigint,
  primary key (project_id, person_id)
);
create index project_attendees_person_idx on public.project_attendees (person_id);

insert into public.project_attendees (project_id, person_id)
select distinct x.project_id, x.person_id
  from (select id as project_id, sales_person_id as person_id from public.projects where sales_person_id is not null
        union
        select id, designer_person_id from public.projects where designer_person_id is not null) x
on conflict (project_id, person_id) do nothing;

create table public.project_procurement_dates (
  project_id bigint not null references public.projects(id) on delete cascade,
  group_code text not null,
  sub_code text not null default '',
  po_date date,
  delivery_date date,
  mode text not null default 'follow',
  updated_at timestamptz not null default now(),
  updated_by text,
  primary key (project_id, group_code, sub_code),
  constraint project_procurement_dates_mode_check check (mode in ('follow', 'own', 'none')),
  constraint project_procurement_dates_order_check check (po_date is null or delivery_date is null or delivery_date >= po_date)
);

create table public.project_design_notes (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  company_id bigint not null default 1 references public.companies(id),
  kind text not null,
  noted_on date not null default current_date,
  requested_by_person_id bigint references public.project_people(id) on delete set null,
  requested_by_text text,
  note text not null,
  created_at timestamptz not null default now(),
  created_by bigint,
  constraint project_design_notes_kind_check check (kind in ('3d', '2d')),
  constraint project_design_notes_note_check check (length(trim(note)) > 0)
);
create index project_design_notes_project_idx on public.project_design_notes (project_id, kind, noted_on desc, id desc);

alter table public.project_design_files
  add column submitted_on date,
  add column next_person_id bigint references public.project_people(id) on delete set null;

alter table public.project_attendees owner to scm_engine;
alter table public.project_procurement_dates owner to scm_engine;
alter table public.project_design_notes owner to scm_engine;
alter table public.project_attendees enable row level security;
alter table public.project_procurement_dates enable row level security;
alter table public.project_design_notes enable row level security;
revoke all on public.project_attendees from anon, authenticated;
revoke all on public.project_procurement_dates from anon, authenticated;
revoke all on public.project_design_notes from anon, authenticated;
