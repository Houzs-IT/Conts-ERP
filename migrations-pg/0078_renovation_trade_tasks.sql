-- REVERSAL: drop table public.project_trade_task_lines; drop table public.project_trade_tasks;
-- Site tasks of a renovation project. A trade task comes from the sales order's WORKS lines (one
-- per trade, electrical twice: first and second fix) and is fulfilled by the subcontractor's
-- purchase order; a template task (trade_code 'INTERNAL:<key>', e.g. QC, touch up) comes from the
-- project type and is done by staff with a tick and a photo. The suggested trade order only lays out
-- new tasks: tasks carry planned dates, may overlap and be reordered, and only overdue dates flag.
-- fulfilment_kind leaves room for a later Production module ('production_order'), not built now.
set local search_path = public, extensions;

create table public.project_trade_tasks (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  stage_key text not null default 'hardware',
  trade_code text not null,
  fix_phase text not null default 'single',
  label text not null,
  seq integer not null default 0,
  fulfilment_kind text not null default 'po',
  supplier_id uuid references scm.suppliers(id) on delete set null,
  purchase_order_id uuid references scm.purchase_orders(id) on delete set null,
  state text not null default 'open',
  skip_reason text,
  skipped_by bigint,
  skipped_at timestamptz,
  skip_source text,
  planned_start date,
  planned_end date,
  actual_start date,
  actual_end date,
  done_by bigint,
  done_at timestamptz,
  completed_by_grn_id uuid references scm.grns(id) on delete set null,
  notes text,
  company_id bigint not null default 1 references public.companies(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_trade_tasks_stage_check check (stage_key in ('design', 'key_permit', 'defect_check',
    'shop_drawings', 'hardware', 'furniture', 'appliances', 'soft_furnishing', 'handover', 'warranty', 'closed')),
  constraint project_trade_tasks_fix_check check (fix_phase in ('single', 'first', 'second')),
  constraint project_trade_tasks_fulfilment_kind_check check (fulfilment_kind in ('po', 'internal')),
  constraint project_trade_tasks_internal_check check (
    (fulfilment_kind = 'internal') = (trade_code like 'INTERNAL:%')
    and (fulfilment_kind <> 'internal' or purchase_order_id is null)),
  constraint project_trade_tasks_state_check check (state in ('open', 'in_progress', 'done', 'skipped')),
  constraint project_trade_tasks_skip_check check (
    (state = 'skipped' and skip_source in ('manual', 'vo_omitted') and skipped_at is not null
      and (skip_source <> 'manual' or (length(trim(coalesce(skip_reason, ''))) >= 3 and skipped_by is not null)))
    or (state <> 'skipped' and skip_reason is null and skipped_by is null and skipped_at is null and skip_source is null)),
  constraint project_trade_tasks_planned_check check (planned_start is null or planned_end is null or planned_end >= planned_start),
  constraint project_trade_tasks_actual_check check (actual_start is null or actual_end is null or actual_end >= actual_start)
);
create unique index project_trade_tasks_trade_unique on public.project_trade_tasks (project_id, trade_code, fix_phase);
create index project_trade_tasks_calendar_idx on public.project_trade_tasks (company_id, planned_start, planned_end);
create index project_trade_tasks_supplier_idx on public.project_trade_tasks (supplier_id) where supplier_id is not null;
create index project_trade_tasks_po_idx on public.project_trade_tasks (purchase_order_id) where purchase_order_id is not null;

create table public.project_trade_task_lines (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.project_trade_tasks(id) on delete cascade,
  so_item_id uuid not null references scm.mfg_sales_order_items(id) on delete cascade,
  purchase_order_item_id uuid references scm.purchase_order_items(id) on delete set null,
  company_id bigint not null default 1 references public.companies(id),
  created_at timestamptz not null default now(),
  constraint project_trade_task_lines_unique unique (task_id, so_item_id)
);
create index project_trade_task_lines_so_item_idx on public.project_trade_task_lines (so_item_id);
create index project_trade_task_lines_po_item_idx on public.project_trade_task_lines (purchase_order_item_id)
  where purchase_order_item_id is not null;

alter table public.project_trade_tasks owner to scm_engine;
alter table public.project_trade_task_lines owner to scm_engine;
alter table public.project_trade_tasks enable row level security;
alter table public.project_trade_task_lines enable row level security;
revoke all on public.project_trade_tasks from anon, authenticated;
revoke all on public.project_trade_task_lines from anon, authenticated;
