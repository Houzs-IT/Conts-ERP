-- REVERSAL: drop table public.project_work_types; (and restore the type check on project_beta_events from migration 0147)
-- Design work (owner, 19 Nov 2026): the works of a renovation project are kept in Project Maintenance instead of the
-- code. The list drives the calendar's Add work types, and the works marked "in design" are the rows of Design
-- progress and the steps of the Design stage, in their order. A bookable work picks a date and time; once its day has
-- passed (after midnight) it is done and that day is recorded. The six built-in works keep their own rule and cannot
-- be removed: Site measure (the booked measure), 3D and 2D (Record approval), Second payment (the money received),
-- Carpentry measure and Site briefing (their booked day). Variants is not a work: the system checks it after the list.
-- APPLY: production through the GitHub workflow "Apply migrations to production" with only=0342, dry run first.

set local search_path = public, scm, extensions;
set local lock_timeout = '5s';

create table if not exists public.project_work_types (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id),
  code text not null check (code ~ '^[a-z0-9_]{1,40}$'),
  label text not null check (length(btrim(label)) between 1 and 60),
  -- booking: done once its booked day has passed; the rest are the built-in rules
  rule text not null default 'booking' check (rule in ('booking', 'measure', 'approve_3d', 'approve_2d', 'payment_2')),
  bookable boolean not null default true,
  in_design boolean not null default false,
  sort_order int not null default 0,
  active boolean not null default true,
  system boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (company_id, code)
);
alter table public.project_work_types owner to scm_engine;
alter table public.project_work_types enable row level security;
grant select, insert, update, delete on public.project_work_types to service_role;
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'pos_app') then grant select on public.project_work_types to pos_app; end if;
end $$;

-- Every company starts with the works the code had: the six design works, then the other calendar types.
insert into public.project_work_types (company_id, code, label, rule, bookable, in_design, sort_order, system)
select c.id, w.code, w.label, w.rule, w.bookable, w.in_design, w.sort_order, w.system
  from public.companies c
  cross join (values
    ('measure',   'Site measure',      'measure',    true,  true,  10, true),
    ('w3d',       '3D',                'approve_3d', true,  true,  20, true),
    ('w2d',       '2D',                'approve_2d', true,  true,  30, true),
    ('payment_2', 'Second payment',    'payment_2',  false, true,  40, true),
    ('carpentry', 'Carpentry measure', 'booking',    true,  true,  50, true),
    ('briefing',  'Site briefing',     'booking',    true,  true,  60, true),
    ('update',    'Drawing update',    'booking',    true,  false, 110, false),
    ('client',    'Client meeting',    'booking',    true,  false, 120, false),
    ('meeting',   'Internal meeting',  'booking',    true,  false, 130, false),
    ('amend',     'Amendment',         'booking',    true,  false, 140, false),
    ('po',        'PO / C.PO',         'booking',    true,  false, 150, false)
  ) as w(code, label, rule, bookable, in_design, sort_order, system)
on conflict (company_id, code) do nothing;

-- Calendar events now take any work type of the list (checked by the API against project_work_types).
alter table public.project_beta_events drop constraint if exists project_beta_events_type_check;

notify pgrst, 'reload schema';
