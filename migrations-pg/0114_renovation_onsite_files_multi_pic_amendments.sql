-- REVERSAL: drop table public.project_design_record_files, public.project_design_record_people, public.project_design_file_people; alter table public.project_design_notes drop column closed_by_file_id, drop column closed_at;
-- Renovation design task, owner feedback of 14 Oct 2026 (after migration 0111).
--
-- * project_design_record_people: an Onsite entry (project_design_records) has several PICs. person_id on the
--   record stays (first PIC) for its other readers; the existing ones are copied here.
-- * project_design_record_files: photos / files attached to an Onsite entry (R2, like design files).
-- * project_design_file_people: a design submission (3D especially) has several PICs. person_id stays (first PIC);
--   the existing ones are copied here.
-- * project_design_notes gains closed_by_file_id / closed_at: a 2D note is an amendment request, open until the next
--   2D version answers it. Existing 2D notes are closed by the first 2D version handed in after them.
set local search_path = public, extensions;

create table public.project_design_record_people (
  record_id bigint not null references public.project_design_records(id) on delete cascade,
  person_id bigint not null references public.project_people(id) on delete cascade,
  primary key (record_id, person_id)
);
insert into public.project_design_record_people (record_id, person_id)
select id, person_id from public.project_design_records where person_id is not null
on conflict do nothing;

create table public.project_design_record_files (
  id bigint generated by default as identity primary key,
  record_id bigint not null references public.project_design_records(id) on delete cascade,
  project_id bigint not null references public.projects(id) on delete cascade,
  file_name text not null,
  content_type text,
  size_bytes bigint,
  r2_key text not null,
  uploaded_by bigint,
  uploaded_at timestamptz not null default now()
);
create index project_design_record_files_record_idx on public.project_design_record_files (record_id, id);

create table public.project_design_file_people (
  file_id bigint not null references public.project_design_files(id) on delete cascade,
  person_id bigint not null references public.project_people(id) on delete cascade,
  primary key (file_id, person_id)
);
insert into public.project_design_file_people (file_id, person_id)
select id, person_id from public.project_design_files where person_id is not null
on conflict do nothing;

alter table public.project_design_notes
  add column closed_by_file_id bigint references public.project_design_files(id) on delete set null,
  add column closed_at timestamptz;

update public.project_design_notes n
   set closed_by_file_id = (
     select f.id from public.project_design_files f
      where f.project_id = n.project_id and f.kind = '2d' and f.uploaded_at > n.created_at
      order by f.uploaded_at, f.id limit 1)
 where n.kind = '2d' and n.closed_by_file_id is null;
update public.project_design_notes n
   set closed_at = (select f.uploaded_at from public.project_design_files f where f.id = n.closed_by_file_id)
 where n.closed_by_file_id is not null and n.closed_at is null;

alter table public.project_design_record_people owner to scm_engine;
alter table public.project_design_record_files owner to scm_engine;
alter table public.project_design_file_people owner to scm_engine;
alter table public.project_design_record_people enable row level security;
alter table public.project_design_record_files enable row level security;
alter table public.project_design_file_people enable row level security;
revoke all on public.project_design_record_people from anon, authenticated;
revoke all on public.project_design_record_files from anon, authenticated;
revoke all on public.project_design_file_people from anon, authenticated;
