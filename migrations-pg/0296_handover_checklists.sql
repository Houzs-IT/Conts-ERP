-- Handover snag list (TODO item 17, after Hookka's QC templates / inspections / pending queue): a company keeps
-- checklist templates (room or area, what to check, what good looks like); a project starts a handover check from one,
-- which copies its items so a later template edit never changes a check already walked. Each item is marked Pass,
-- Fail or Not applicable; a Fail is reported as a defect with its photo (project_defects, the Beta Defects pipeline)
-- and the item keeps the defect's id. A check may stay open with items not yet marked and be finished on a later
-- visit; it does not stop the handover (the existing rule, every defect closed first, is unchanged).
--
-- One default template, "Renovation handover", is written for each company that has none.
--
-- APPLY: production before merging (begin; this file; insert into public.pos_migrations ...; commit). The screens
-- answer "not switched on yet" until it is applied. New tables owned by scm_engine like project_handovers (0080).
select demo.drop_views();
set local search_path = public, extensions;
set local lock_timeout = '5s';

create table if not exists public.handover_checklist_templates (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id),
  name text not null,
  active boolean not null default true,
  created_by bigint,
  created_at timestamptz not null default now(),
  updated_by bigint,
  updated_at timestamptz not null default now(),
  constraint handover_checklist_templates_name_check check (length(trim(name)) between 1 and 120)
);
create unique index if not exists handover_checklist_templates_name_idx
  on public.handover_checklist_templates (company_id, lower(name)) where active;

create table if not exists public.handover_checklist_template_items (
  id bigint generated by default as identity primary key,
  template_id bigint not null references public.handover_checklist_templates(id) on delete cascade,
  sequence integer not null,
  area text,
  item text not null,
  criteria text,
  constraint handover_checklist_template_items_item_check check (length(trim(item)) between 1 and 300),
  constraint handover_checklist_template_items_seq_unique unique (template_id, sequence)
);

create table if not exists public.project_handover_checks (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  company_id bigint not null references public.companies(id),
  template_id bigint references public.handover_checklist_templates(id) on delete set null,
  template_name text not null,
  started_by bigint,
  started_at timestamptz not null default now(),
  completed_by bigint,
  completed_at timestamptz,
  constraint project_handover_checks_completed_check check ((completed_at is null) = (completed_by is null))
);
create index if not exists project_handover_checks_project_idx on public.project_handover_checks (project_id);
create index if not exists project_handover_checks_open_idx on public.project_handover_checks (company_id) where completed_at is null;

create table if not exists public.project_handover_check_items (
  id bigint generated by default as identity primary key,
  check_id bigint not null references public.project_handover_checks(id) on delete cascade,
  sequence integer not null,
  area text,
  item text not null,
  criteria text,
  result text,
  note text,
  defect_id bigint references public.project_defects(id) on delete set null,
  checked_by bigint,
  checked_at timestamptz,
  constraint project_handover_check_items_result_check check (result is null or result in ('pass', 'fail', 'na')),
  constraint project_handover_check_items_checked_check check ((result is null) = (checked_at is null)),
  constraint project_handover_check_items_seq_unique unique (check_id, sequence)
);
create index if not exists project_handover_check_items_defect_idx on public.project_handover_check_items (defect_id) where defect_id is not null;

