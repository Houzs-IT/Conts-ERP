-- REVERSAL: alter table public.projects drop constraint projects_project_type_id_fkey; drop table public.project_stages; drop table public.project_types;
-- Project types (Full renovation, Airbnb package, Carpentry only) name which of the 11 stages a
-- project runs, and project_stages holds one row per stage of a project. Stored state is only what a
-- person decided (started, done, skipped by hand with a reason); skips that follow from the type or
-- from the sales order's contents are worked out when the project is read, so a variation order
-- that adds lines re-opens a stage without anyone touching this table.
set local search_path = public, extensions;

create table public.project_types (
  id bigint generated by default as identity primary key,
  slug text not null,
  name text not null,
  stage_keys text[] not null,
  checklist_template_id bigint references public.project_checklist_templates(id) on delete set null,
  sort_order integer not null default 0,
  active boolean not null default true,
  company_id bigint not null default 1 references public.companies(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_types_slug_unique unique (company_id, slug),
  constraint project_types_stage_keys_check check (
    stage_keys <@ array['design', 'key_permit', 'defect_check', 'shop_drawings', 'hardware', 'furniture',
      'appliances', 'soft_furnishing', 'handover', 'warranty', 'closed']::text[]
    and stage_keys @> array['design', 'handover', 'closed']::text[])
);

alter table public.projects
  add constraint projects_project_type_id_fkey foreign key (project_type_id) references public.project_types(id) on delete set null;

create table public.project_stages (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  stage_key text not null,
  seq integer not null,
  in_type boolean not null default true,
  state text not null default 'not_started',
  started_at timestamptz,
  started_by bigint,
  done_at timestamptz,
  done_by bigint,
  skip_reason text,
  skipped_by bigint,
  skipped_at timestamptz,
  planned_start date,
  planned_end date,
  company_id bigint not null default 1 references public.companies(id),
  updated_at timestamptz not null default now(),
  constraint project_stages_project_stage_unique unique (project_id, stage_key),
  constraint project_stages_stage_key_check check (stage_key in ('design', 'key_permit', 'defect_check',
    'shop_drawings', 'hardware', 'furniture', 'appliances', 'soft_furnishing', 'handover', 'warranty', 'closed')),
  constraint project_stages_state_check check (state in ('not_started', 'in_progress', 'done', 'skipped')),
  -- A skip always carries who, when and why; any other state carries none of them.
  constraint project_stages_skip_check check (
    (state = 'skipped' and length(trim(coalesce(skip_reason, ''))) >= 3 and skipped_by is not null and skipped_at is not null)
    or (state <> 'skipped' and skip_reason is null and skipped_by is null and skipped_at is null)),
  constraint project_stages_unskippable_check check (not (state = 'skipped' and stage_key in ('design', 'handover', 'closed'))),
  constraint project_stages_planned_check check (planned_start is null or planned_end is null or planned_end >= planned_start)
);
create index project_stages_project_idx on public.project_stages (project_id, seq);

alter table public.project_types owner to scm_engine;
alter table public.project_stages owner to scm_engine;
alter table public.project_types enable row level security;
alter table public.project_stages enable row level security;
revoke all on public.project_types from anon, authenticated;
revoke all on public.project_stages from anon, authenticated;
