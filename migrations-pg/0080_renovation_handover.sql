-- Handover: the customer accepts the unit with a signed handover form (one per project). It can only
-- be signed once every snag on the list is closed. Snags and the developer defect check reuse the
-- engine's project_defects (phase 'defect_check' or 'snag'), gaining a room, a due date and who
-- closed them.
set local search_path = public, extensions;

create table public.project_handovers (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  customer_signer_name text not null,
  customer_signature_r2_key text not null,
  staff_user_id bigint,
  signed_at timestamptz not null default now(),
  keys_returned integer,
  access_cards_returned integer,
  deposit_refund_note text,
  notes text,
  lat double precision,
  lng double precision,
  accuracy_m double precision,
  located_at timestamptz,
  company_id bigint not null default 1 references public.companies(id),
  created_at timestamptz not null default now(),
  constraint project_handovers_project_unique unique (project_id),
  constraint project_handovers_signer_check check (length(trim(customer_signer_name)) > 0),
  constraint project_handovers_counts_check check (coalesce(keys_returned, 0) >= 0 and coalesce(access_cards_returned, 0) >= 0),
  constraint project_handovers_location_check check (
    (lat is null and lng is null) or (lat between -90 and 90 and lng between -180 and 180 and located_at is not null))
);

alter table public.project_defects
  add column stage_key text,
  add column location text,
  add column due_date date,
  add column closed_at timestamptz,
  add column closed_by bigint,
  add column company_id bigint not null default 1 references public.companies(id);
alter table public.project_defects
  add constraint project_defects_closed_check check ((closed_at is null) = (closed_by is null));
create index project_defects_project_open_idx on public.project_defects (project_id) where closed_at is null and archived_at is null;

alter table public.project_handovers owner to scm_engine;
alter table public.project_handovers enable row level security;
revoke all on public.project_handovers from anon, authenticated;
