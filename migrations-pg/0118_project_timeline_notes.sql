-- REVERSAL: drop table public.project_timeline_notes;
-- Renovation project Timeline (owner, 15 Oct 2026): the same card as a service case's timeline, on the project page.
-- Its automatic "System" entries are read from the history the project already keeps (project_activity,
-- project_flow_log, key moves, design records, files and notes, the project's POs / GRs / DOs), so nothing is copied.
-- Only the notes people add by hand are new, and they live here: one row per note, with its type (the filter chip
-- it shows under) and who wrote it. A note is archived (hidden), never deleted.
--
-- APPLY: by hand, staging first, then production (node scripts/migrate-pg.mjs --env-file=<file>, dry-run first).
-- Until it is applied the Timeline still shows the System entries; adding a note answers "not ready".
set local search_path = public, extensions;

create table public.project_timeline_notes (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  company_id bigint not null default 1 references public.companies(id),
  note_type text not null,
  note text not null,
  created_by bigint,
  created_at timestamptz not null default now(),
  archived_at timestamptz,
  archived_by bigint,
  constraint project_timeline_notes_type_check check (note_type in ('customer', 'design', 'supplier', 'site', 'sales')),
  constraint project_timeline_notes_note_check check (length(btrim(note)) between 1 and 2000)
);
create index project_timeline_notes_project_idx on public.project_timeline_notes (project_id, created_at desc);

alter table public.project_timeline_notes owner to scm_engine;
alter table public.project_timeline_notes enable row level security;
revoke all on public.project_timeline_notes from anon, authenticated;
