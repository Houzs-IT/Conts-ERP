-- Customer and property information shared by a renovation sales order and its project (owner, 14 Oct 2026).
--
-- * The project is the master record: customer name / phone / email, site address, building and unit already
--   live on public.projects (migration 0075); this adds the property: property type, layout (a label plus the
--   bedroom and bathroom counts it stands for) and built-up area in square feet.
-- * The sales order keeps its own copy of the same fields for printing (address, phone and project_id were already
--   there); saving the SO writes the shared fields back to its project, and editing the project refreshes the SOs
--   linked to it that are still open (rule: engine/backend/src/scm/shared/renovation-property.ts).
-- * Two pick lists per company, edited in Project Maintenance and read by both the SO form and the project:
--   project_property_types (Condo, Landed, ...) and project_layouts (Studio, 1 bed 1 bath, ...). The SO and the
--   project store the chosen label and numbers, not the list id, so renaming or switching off a list row never
--   changes a saved document.
--
-- APPLY: by hand, staging first, then production (node scripts/migrate-pg.mjs --env-file=<file>, dry-run first).
-- Until it is applied the engine keeps showing Houzs's sales order form (the property lists read as not ready).
set local search_path = public, extensions;

create table public.project_property_types (
  id bigint generated by default as identity primary key,
  company_id bigint not null default 1 references public.companies(id),
  label text not null,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_property_types_label_check check (length(trim(label)) > 0)
);
create unique index project_property_types_label_unique on public.project_property_types (company_id, lower(label));

create table public.project_layouts (
  id bigint generated by default as identity primary key,
  company_id bigint not null default 1 references public.companies(id),
  label text not null,
  bedrooms integer not null,
  bathrooms integer not null,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_layouts_label_check check (length(trim(label)) > 0),
  constraint project_layouts_bedrooms_check check (bedrooms between 0 and 20),
  constraint project_layouts_bathrooms_check check (bathrooms between 0 and 20)
);
create unique index project_layouts_label_unique on public.project_layouts (company_id, lower(label));

insert into public.project_property_types (company_id, label, sort_order)
select co.id, t.label, t.sort_order
  from public.companies co
 cross join (values ('Condo', 10), ('Landed', 20), ('Serviced apartment', 30), ('Commercial', 40), ('Other', 50))
       as t(label, sort_order)
on conflict do nothing;

insert into public.project_layouts (company_id, label, bedrooms, bathrooms, sort_order)
select co.id, l.label, l.bedrooms, l.bathrooms, l.sort_order
  from public.companies co
 cross join (values ('Studio', 0, 1, 10), ('1 bed 1 bath', 1, 1, 20), ('2 bed 2 bath', 2, 2, 30),
                    ('3 bed 2 bath', 3, 2, 40), ('4 bed 3 bath', 4, 3, 50), ('5 bed 4 bath', 5, 4, 60))
       as l(label, bedrooms, bathrooms, sort_order)
on conflict do nothing;

alter table public.projects
  add column property_type text,
  add column layout_label text,
  add column bedrooms integer,
  add column bathrooms integer,
  add column built_up_sqft numeric(10, 2);
alter table public.projects
  add constraint projects_bedrooms_check check (bedrooms is null or bedrooms between 0 and 20),
  add constraint projects_bathrooms_check check (bathrooms is null or bathrooms between 0 and 20),
  add constraint projects_built_up_sqft_check check (built_up_sqft is null or built_up_sqft > 0);

alter table scm.mfg_sales_orders
  add column building text,
  add column unit_no text,
  add column property_type text,
  add column layout_label text,
  add column bedrooms integer check (bedrooms is null or bedrooms between 0 and 20),
  add column bathrooms integer check (bathrooms is null or bathrooms between 0 and 20),
  add column built_up_sqft numeric(10, 2) check (built_up_sqft is null or built_up_sqft > 0);

alter table public.project_property_types owner to scm_engine;
alter table public.project_layouts owner to scm_engine;
alter table public.project_property_types enable row level security;
alter table public.project_layouts enable row level security;
revoke all on public.project_property_types from anon, authenticated;
revoke all on public.project_layouts from anon, authenticated;
