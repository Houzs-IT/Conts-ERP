-- Existing tasks get the category their trade (or template key) maps to; a contract CLEANING line is the post-reno clean.
update public.project_trade_tasks t
   set category_code = coalesce(
         (select c.code from public.project_task_categories c
           where c.company_id = t.company_id and t.trade_code like 'INTERNAL:%' and c.internal_key = substring(t.trade_code from 10)),
         (select c.code from public.project_task_categories c
           where c.company_id = t.company_id and c.trade_code = t.trade_code and c.fix_phase = t.fix_phase and c.trade_default),
         case when t.trade_code = 'CLEANING' then 'POST_RENO_CLEANING' end)
 where t.category_code is null;

