-- Site tasks, simplified (owner decisions 11 Oct 2026):
--
-- * project_task_categories: the site task vocabulary in the owner's Notion wording (study section 2.2), one row per
--   category per company, mapped onto a WORKS trade (trade_code + fix_phase) or a template task (internal_key), or
--   neither (a task by itself: carpentry, curtain, deliveries...). Same rows as TASK_CATEGORIES in
--   engine/backend/src/scm/shared/renovation-stages.ts (tests/renovationTaskCategoriesSeed.test.ts compares them).
--   Label, order and active are the company's to change; code, stage and mapping are not.
-- * project_trade_tasks: a category (category_code), an occurrence so one category may repeat on a project (Notion has
--   repeats), and source / source_ref for the Notion importer. A task is fulfilled by a purchase order
--   (subcontractor or supplier, completes on receipt) or by our own people (fulfilment_kind 'internal': template tasks
--   and in-house crew, ticked done); an internal task never has a PO. There is no production order.
-- * project_trade_task_assignees: the people (in-house crew) on a task, one or more.
set local search_path = public, extensions;

create table public.project_task_categories (
  id bigint generated by default as identity primary key,
  company_id bigint not null default 1 references public.companies(id),
  code text not null,
  label text not null,
  stage_key text not null,
  trade_code text,
  fix_phase text not null default 'single',
  internal_key text,
  trade_default boolean not null default false,
  sort_order integer not null default 0,
  active boolean not null default true,
  notion boolean not null default true,
  updated_at timestamptz not null default now(),
  constraint project_task_categories_unique unique (company_id, code),
  constraint project_task_categories_label_check check (length(trim(label)) > 0),
  constraint project_task_categories_stage_check check (stage_key in ('design', 'key_permit', 'defect_check',
    'shop_drawings', 'hardware', 'furniture', 'appliances', 'soft_furnishing', 'handover', 'warranty', 'closed')),
  constraint project_task_categories_fix_check check (fix_phase in ('single', 'first', 'second')),
  constraint project_task_categories_map_check check (trade_code is null or internal_key is null)
);

