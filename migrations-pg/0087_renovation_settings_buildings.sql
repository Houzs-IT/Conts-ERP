-- ── Renovation contractors (each one an engine supplier) ─────────────────
create table public.project_reno_contractors (
  id bigint generated by default as identity primary key,
  company_id bigint not null default 1 references public.companies(id),
  name text not null,
  trade text,
  supplier_id uuid not null references scm.suppliers(id) on delete restrict,
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint project_reno_contractors_name_check check (length(trim(name)) > 0)
);
create unique index project_reno_contractors_name_unique on public.project_reno_contractors (company_id, upper(trim(name)));
create unique index project_reno_contractors_supplier_unique on public.project_reno_contractors (company_id, supplier_id);

do $$
declare
  co record;
  v record;
  sup uuid;
  v_code text;
begin
  for co in select id from public.companies loop
    for v in
      select * from (values
        ('YILLON', 'Carpentry', 'Subcontractor', 10), ('IDRESS', 'Curtains', 'Subcontractor', 20),
        ('KHALIQ', 'QC', 'Subcontractor', 30), ('LITTLE BUILDER', 'Kitchen top', 'Subcontractor', 40),
        ('SUNNY', null, 'Subcontractor', 50), ('ELEGANZ-TIM', null, 'Subcontractor', 60),
        ('KIM SENG', null, 'Subcontractor', 70), ('YJ', null, 'Subcontractor', 80), ('BABU', null, 'Subcontractor', 90),
        ('OUTSOURCE', 'General works', 'Subcontractor', 100), ('HOUZS', 'Furniture supplier', 'Supplier', 110)
      ) as t(name, trade, kind, ord)
    loop
      if exists (select 1 from public.project_reno_contractors where company_id = co.id and upper(trim(name)) = v.name) then
        continue;
      end if;
      v_code := 'SC-' || trim(both '-' from regexp_replace(v.name, '[^A-Z0-9]+', '-', 'g'));
      select s.id into sup from scm.suppliers s where s.company_id = co.id and (s.code = v_code or upper(trim(s.name)) = v.name)
       order by (s.code = v_code) desc limit 1;
      if sup is null then
        insert into scm.suppliers (code, name, supplier_type, category, company_id)
        values (v_code, v.name, v.kind, v.trade, co.id) returning id into sup;
      end if;
      insert into public.project_reno_contractors (company_id, name, trade, supplier_id, sort_order)
      values (co.id, v.name, v.trade, sup, v.ord)
      on conflict do nothing;
    end loop;
  end loop;
end $$;

