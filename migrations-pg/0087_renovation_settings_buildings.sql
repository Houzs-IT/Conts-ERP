-- Renovation settings and the new-project form (owner requirements 11 Oct 2026):
--
-- * project_property_types: Condo, Landed, Serviced apartment, Commercial, Others (editable per company).
-- * project_buildings: the building list the new-project form picks from (name, state, default property type),
--   seeded with the 57 "Building Name" options of the owner's Notion project board; state is left blank where the
--   name does not say it. source / source_ref let the Notion importer upsert.
-- * project_types.sla_days: days from the project's start to its SLA due date (shown on the board and the project,
--   flagged when passed). Full renovation 45, carpentry only 30, Airbnb package 21, and a new Design only type 14.
-- * projects: building_id, property_type_id, bedrooms, bathrooms, built_up_sqft, brand_id. The text columns
--   building / unit_no / customer_name / state / brand stay filled too (the board and the Notion importer read them).
-- * project_reno_contractors: the renovation subcontractors (Notion "Contractor" list). Each one IS an engine supplier
--   (supplier_id, required): sales order lines bind a supplier and the SO -> PO split groups lines by it, so a
--   subcontractor must exist as a supplier to receive a purchase order. The seed reuses a supplier of the same code or
--   name and creates the rest with code SC-<NAME>. In-house crew are people (project_people, role site_crew), not
--   contractors.
