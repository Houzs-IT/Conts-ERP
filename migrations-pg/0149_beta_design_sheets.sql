-- REVERSAL: drop table public.project_design_sheets;
-- Beta Drawings, 2D as a set of sheets (owner, 24 Oct 2026). A 2D version (a project_design_files row, kind '2d') can
-- now hold several sheets: the first upload is usually the whole set, a later version holds only the sheets that
-- changed. The set a version stands for is, per sheet name, the newest sheet up to that version; every older sheet
-- stays as history. A 2D version with no rows here is one file (its own r2_key or link), as before.
-- The version row keeps r2_key = its first sheet, so screens that open a version's file still open something.
--
-- APPLY: by hand, staging first, then production (node scripts/migrate-pg.mjs --env-file=<file>, dry-run first).
set local search_path = public, extensions;

create table public.project_design_sheets (
  id bigint generated by default as identity primary key,
  file_id bigint not null references public.project_design_files(id) on delete cascade,
  project_id bigint not null references public.projects(id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 120),
  file_name text not null,
  content_type text,
  size_bytes bigint,
  r2_key text not null,
  uploaded_by bigint,
  uploaded_at timestamptz not null default now()
);
create index project_design_sheets_project_idx on public.project_design_sheets (project_id, file_id, id);
alter table public.project_design_sheets enable row level security;
