import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import postgres, { type Sql } from "postgres";
import { Hono } from "hono";
import { afterAll, beforeAll, describe, expect, test } from "vitest";
import { d1Compat } from "../src/db/d1-compat";
import handover from "../src/routes/renovationBetaHandover";
import renovationBeta from "../src/routes/renovationBeta";

/* Migration 0296 and every statement of the handover checklist routes, run for real through the engine's D1 adapter.
   The tables 0296 points at (companies, projects, project_defects, project_activity, users, project_people) are reduced
   to the columns these routes read, with their real types (0045, 0080, 0146, 0151; project_defects.archived_at is
   text). SKIPPED without TEST_DATABASE_URL, which must be a throwaway database: this drops schema public. */

const url = process.env.TEST_DATABASE_URL ?? "";
const describePg = url ? describe : describe.skip;
let sql: Sql;

function app() {
  const outer = new Hono();
  outer.use("*", async (c, next) => {
    const perms = ["projects.write", "projects.manage"];
    c.set("user" as never, { id: 5, permissions: perms, permissions_set: new Set(perms), page_access: { "projects.list": "full" } } as never);
    c.set("companyId" as never, 1 as never);
    await next();
  });
  outer.route("/api/beta", handover as never);
  outer.route("/api/beta", renovationBeta as never);
  return outer;
}

async function call(method: string, path: string, body?: unknown) {
  const res = await app().request(`/api/beta${path}`, {
    method, headers: { "content-type": "application/json" }, body: body === undefined ? undefined : JSON.stringify(body),
  }, { DB: d1Compat(() => sql) } as never);
  const text = await res.text();
  let json: any = null;
  try { json = JSON.parse(text); } catch { json = text; }
  return { status: res.status, json };
}

describePg("handover checklists on real Postgres", () => {
  beforeAll(async () => {
    sql = postgres(url, { max: 1, prepare: false, fetch_types: false, onnotice: () => {} });
    await sql.unsafe(`
      do $$ begin
        if not exists (select 1 from pg_roles where rolname = 'scm_engine') then create role scm_engine; end if;
        if not exists (select 1 from pg_roles where rolname = 'service_role') then create role service_role; end if;
        if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon; end if;
        if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated; end if;
      end $$;
      drop schema if exists public cascade; create schema public; grant usage, create on schema public to scm_engine;
      drop schema if exists demo cascade; create schema demo;
      create schema if not exists extensions;
      create function demo.drop_views() returns void language sql as 'select';
      create function demo.sync() returns void language sql as 'select';
      create table public.companies (id bigint primary key);
      insert into public.companies values (1), (2);
      create table public.users (id bigint primary key, name text);
      insert into public.users values (5, 'Wei');
      create table public.project_people (id bigint primary key, name text, phone text, company_id bigint);
      create table public.projects (id bigint primary key, code text, name text, customer_name text, project_kind text, archived_at text,
        company_id bigint references public.companies(id), planned_handover_date date);
      insert into public.projects values (7, 'RN-1', 'Maple', 'Tan', 'renovation', null, 1, null), (8, 'RN-2', 'Oak', 'Lim', 'renovation', null, 2, null);
      create table public.project_defects (id bigint generated by default as identity primary key, project_id bigint not null, phase text not null,
        reported_by_role text not null, item_description text, photo_r2_key text, reported_by bigint, reported_at text, resolved bigint, archived_at text,
        stage_key text, location text, due_date date, closed_at timestamptz, closed_by bigint, company_id bigint not null default 1,
        trade text, fixed_at timestamptz, fixed_by bigint, after_photo_r2_key text, redo_count integer not null default 0,
        assignee_person_id bigint references public.project_people(id) on delete set null);
      create table public.project_activity (id bigint generated by default as identity primary key, project_id bigint not null, action text not null,
        from_value text, to_value text, note text, user_id bigint, created_at text, archived_at text, company_id bigint default 1 not null);
    `);
    const file = readFileSync(resolve(__dirname, "../../../migrations-pg/0296_handover_checklists.sql"), "utf8");
    await sql.begin((tx) => tx.unsafe(file));
  });
  afterAll(async () => { await sql?.end(); });

  test("0296 seeds the default checklist for each company and the routes read it", async () => {
    const n = await sql`select company_id::int as c, count(i.id)::int as items from handover_checklist_templates t join handover_checklist_template_items i on i.template_id = t.id group by 1 order by 1`;
    expect(n).toEqual([{ c: 1, items: 16 }, { c: 2, items: 16 }]);
    const r = await call("GET", "/handover-templates");
    expect(r.status).toBe(200);
    expect(r.json.templates).toHaveLength(1);
    expect(r.json.templates[0].items[0]).toMatchObject({ area: "Main door", item: "Door, lock and keys" });
  });

  let templateId = 0;
  test("a checklist is created and edited with its items in order", async () => {
    const made = await call("POST", "/handover-templates", { name: "Condo", items: [{ area: "Kitchen", item: "Sink" }, { area: "Bath", item: "Tiles", criteria: "No cracks" }] });
    expect(made.status, JSON.stringify(made.json)).toBe(201);
    templateId = made.json.id;
    const edited = await call("PUT", `/handover-templates/${templateId}`, { name: "Condo", items: [{ area: "Bath", item: "Tiles" }, { area: "Kitchen", item: "Sink" }, { item: "Keys" }] });
    expect(edited.status, JSON.stringify(edited.json)).toBe(200);
    const rows = await sql`select sequence, area, item from handover_checklist_template_items where template_id = ${templateId} order by sequence`;
    expect(rows.map((r) => [r.sequence, r.area, r.item])).toEqual([[1, "Bath", "Tiles"], [2, "Kitchen", "Sink"], [3, null, "Keys"]]);
    expect((await call("POST", "/handover-templates", { name: "condo", items: [{ item: "x" }] })).json).toMatchObject({ error: "name_taken" });
  });

  let checkId = 0;
  let items: Array<{ id: number; item: string }> = [];
  test("a check copies the items; a second open check is refused, by the route and by the index", async () => {
    const started = await call("POST", "/projects/7/handover-checks", { templateId });
    expect(started.status, JSON.stringify(started.json)).toBe(201);
    checkId = started.json.id;
    expect((await call("POST", "/projects/7/handover-checks", { templateId })).json).toMatchObject({ error: "check_open" });
    await expect(sql`insert into project_handover_checks (project_id, company_id, template_name) values (7, 1, 'x')`).rejects.toMatchObject({ code: "23505" });
    const read = await call("GET", "/projects/7/handover-checks");
    expect(read.status, JSON.stringify(read.json)).toBe(200);
    items = read.json.checks[0].items;
    expect(items.map((i) => i.item)).toEqual(["Tiles", "Sink", "Keys"]);
    expect(read.json.checks[0].progress).toMatchObject({ total: 3, open: 3 });
  });

  test("Pass and N/A mark, clear unmarks; Finish waits for every item", async () => {
    expect((await call("POST", `/handover-check-items/${items[0]!.id}`, { result: "pass" })).status).toBe(200);
    expect((await call("POST", `/handover-check-items/${items[2]!.id}`, { result: "na", note: "no keys yet" })).status).toBe(200);
    const fin = await call("POST", `/handover-checks/${checkId}/finish`);
    expect(fin.status).toBe(409);
    expect(fin.json).toMatchObject({ error: "items_unchecked", progress: { open: 1 } });
  });

  let defectId = 0;
  test("a failed item is reported as a defect in one statement; a second report for it writes nothing", async () => {
    const report = { location: "Kitchen", description: "Sink: leaks", photoKey: "renovation/7/defect-a.jpg", checkItemId: items[1]!.id };
    const r = await call("POST", "/projects/7/defects", report);
    expect(r.status, JSON.stringify(r.json)).toBe(201);
    defectId = r.json.id;
    const it = (await sql`select result, defect_id::int as d from project_handover_check_items where id = ${items[1]!.id}`)[0]!;
    expect(it).toEqual({ result: "fail", d: defectId });
    const before = (await sql`select count(*)::int as n from project_defects`)[0]!.n;
    const again = await call("POST", "/projects/7/defects", report);
    expect(again.status).toBe(409);
    expect((await sql`select count(*)::int as n from project_defects`)[0]!.n).toBe(before);
    // A Fail cannot be re-marked from the check.
    expect((await call("POST", `/handover-check-items/${items[1]!.id}`, { result: "pass" })).json).toMatchObject({ error: "defect_raised" });
  });

  test("the lock statement itself writes nothing when the item is already linked (race past the pre-check)", async () => {
    const db = d1Compat(() => sql);
    const before = (await sql`select count(*)::int as n from project_defects`)[0]!.n;
    // The same statement shape the route sends, straight at the database.
    const row = await db.prepare(
      `WITH lk AS (SELECT i.id FROM project_handover_check_items i JOIN project_handover_checks k ON k.id = i.check_id
                    WHERE i.id = ?::bigint AND k.project_id = ?::bigint AND k.completed_at IS NULL AND i.defect_id IS NULL FOR UPDATE OF i, k),
            d AS (INSERT INTO project_defects (project_id, phase, reported_by_role, item_description, company_id) SELECT 7, 'snag', 'supervisor', 'x', 1 FROM lk RETURNING id)
       SELECT id::int AS id FROM d`,
    ).bind(items[1]!.id, 7).first();
    expect(row).toBeNull();
    expect((await sql`select count(*)::int as n from project_defects`)[0]!.n).toBe(before);
  });

  test("the queue lists the open defect and the open check", async () => {
    const q = await call("GET", "/defect-queue");
    expect(q.status, JSON.stringify(q.json)).toBe(200);
    expect(q.json.checksReady).toBe(true);
    expect(q.json.defects.map((d: { id: number }) => d.id)).toEqual([defectId]);
    expect(q.json.checks[0]).toMatchObject({ id: checkId, total: 3, checked: 3, failed: 1 });
  });

  test("Finish, then marks are refused; Reopen; an archived defect reads as archived", async () => {
    const fin = await call("POST", `/handover-checks/${checkId}/finish`);
    expect(fin.status, JSON.stringify(fin.json)).toBe(200);
    expect((await call("POST", `/handover-check-items/${items[0]!.id}`, { result: null })).json).toMatchObject({ error: "check_finished" });
    const other = await call("POST", "/projects/7/handover-checks", { templateId });
    expect(other.status).toBe(201);
    expect((await call("POST", `/handover-checks/${checkId}/reopen`)).json).toMatchObject({ error: "check_open" });
    expect((await call("POST", `/handover-checks/${other.json.id}/remove`)).status).toBe(200);
    expect((await call("POST", `/handover-checks/${checkId}/reopen`)).status).toBe(200);
    await sql`update project_defects set archived_at = '2026-11-10T00:00:00Z' where id = ${defectId}`;
    const read = await call("GET", "/projects/7/handover-checks");
    expect(read.json.checks[0].items.find((i: { id: number }) => i.id === items[1]!.id)).toMatchObject({ defectId, defectState: "archived" });
  });

  test("another company's project and template are not reachable", async () => {
    expect((await call("GET", "/projects/8/handover-checks")).status).toBe(404);
    const t2 = (await sql`select id::int as id from handover_checklist_templates where company_id = 2`)[0]!.id;
    expect((await call("PUT", `/handover-templates/${t2}`, { name: "x", items: [{ item: "y" }] })).status).toBe(404);
  });
});
