export interface PortalDates {
  /** 26 Oct 2026 */ day: (isoDate: string) => string;
  /** 26 Oct */ short: (isoDate: string) => string;
  /** Mon 26 Oct */ weekday: (isoDate: string) => string;
  /** October 2026 */ month: (period: string) => string;
  /** 26 Oct 14:05, from an instant */ stamp: (iso: string) => string;
}

/** Month and weekday names a phone's browser may not carry: Chrome's date data has no Burmese, so it falls back to English. */
const OWN_NAMES: Partial<Record<PortalLang, { months: readonly string[]; weekdays: readonly string[] }>> = {
  my: {
    months: ['ဇန်နဝါရီ', 'ဖေဖော်ဝါရီ', 'မတ်', 'ဧပြီ', 'မေ', 'ဇွန်', 'ဇူလိုင်', 'ဩဂုတ်', 'စက်တင်ဘာ', 'အောက်တိုဘာ', 'နိုဝင်ဘာ', 'ဒီဇင်ဘာ'],
    weekdays: ['တနင်္ဂနွေ', 'တနင်္လာ', 'အင်္ဂါ', 'ဗုဒ္ဓဟူး', 'ကြာသပတေး', 'သောကြာ', 'စနေ'],
  },
};
const mytDate = (iso: string): string => new Date(Date.parse(iso) + 8 * 3_600_000).toISOString().slice(0, 10);

/** Dates in the phone's language: "26 Oct 2026", "26 Okt 2026", "2026年10月26日"; a pay month as "October 2026". */
export function usePortalDates(): PortalDates {
  const lang = usePortalLang();
  return useMemo(() => {
    const own = OWN_NAMES[lang];
    const at = (d: string) => ({ y: d.slice(0, 4), m: Number(d.slice(5, 7)) - 1, d: Number(d.slice(8, 10)) });
    const fmt = (d: string, opts: Intl.DateTimeFormatOptions): string => dateIn(LOCALE[lang], d, opts);
    const short = (d: string): string => { const p = at(d); return own ? `${p.d} ${own.months[p.m]}` : fmt(d, { day: 'numeric', month: 'short' }); };
    return {
      day: d => { const p = at(d); return own ? `${p.d} ${own.months[p.m]} ${p.y}` : fmt(d, { day: 'numeric', month: 'short', year: 'numeric' }); },
      short,
      weekday: d => {
        const p = at(d);
        return own ? `${own.weekdays[new Date(Date.UTC(Number(p.y), p.m, p.d)).getUTCDay()]} ${p.d} ${own.months[p.m]}` : fmt(d, { weekday: 'short', day: 'numeric', month: 'short' });
      },
      month: period => (own ? `${own.months[Number(period.slice(5, 7)) - 1]} ${period.slice(0, 4)}` : fmt(`${period}-15`, { month: 'long', year: 'numeric' })),
      stamp: iso => `${short(mytDate(iso))} ${time(iso)}`,
    };
  }, [lang]);
}
